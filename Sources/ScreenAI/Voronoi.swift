/// voronoi_diagram<double>: cells (one per input point), vertices and half-edges, linked by index (-1: none).
struct VoronoiDiagram {
    struct Cell {
        /// Index of the input point.
        var source: Int
        var incidentEdge = -1
    }

    struct Vertex {
        var x: Double, y: Double
        var incidentEdge = -1
    }

    struct Edge {
        var cell: Int
        /// The vertex the edge starts at (-1: at infinity).
        var vertex = -1
        var twin = -1, next = -1, prev = -1
    }

    var cells: [Cell] = []
    var vertices: [Vertex] = []
    var edges: [Edge] = []

    /// The next edge around the start vertex, counterclockwise.
    func rotNext(_ e: Int) -> Int { edges[edges[e].prev].twin }
    func rotPrev(_ e: Int) -> Int { edges[edges[e].twin].next }

    /// The diagram of `points` (each at most once).
    init(points: [(x: Int32, y: Int32)]) {
        var builder = VoronoiBuilder(points: points)
        builder.construct(&self)
    }

    // MARK: Building (voronoi_diagram's _insert_new_edge and _build)

    fileprivate init() {}

    fileprivate mutating func insertEdge(_ site1: VoronoiSite, _ site2: VoronoiSite) -> (Int, Int) {
        let e1 = edges.count, e2 = e1 + 1
        if cells.isEmpty { cells.append(Cell(source: site1.initialIndex)) }
        cells.append(Cell(source: site2.initialIndex))
        edges.append(Edge(cell: site1.sortedIndex, twin: e2))
        edges.append(Edge(cell: site2.sortedIndex, twin: e1))
        return (e1, e2)
    }

    fileprivate mutating func insertEdge(_ site1: VoronoiSite, _ site3: VoronoiSite, _ circle: VoronoiCircle,
                                         _ e12: Int, _ e23: Int) -> (Int, Int) {
        let v = vertices.count
        vertices.append(Vertex(x: circle.x, y: circle.y))
        edges[e12].vertex = v
        edges[e23].vertex = v
        let n1 = edges.count, n2 = n1 + 1
        edges.append(Edge(cell: site1.sortedIndex, twin: n2))
        edges.append(Edge(cell: site3.sortedIndex, vertex: v, twin: n1))
        edges[e12].prev = n1
        edges[n1].next = e12
        edges[edges[e12].twin].next = e23
        edges[e23].prev = edges[e12].twin
        edges[edges[e23].twin].next = n2
        edges[n2].prev = edges[e23].twin
        return (n1, n2)
    }

    private mutating func removeEdge(_ edge: Int) {
        let vertex = edges[edge].vertex
        let twin = edges[edge].twin
        var updated = rotNext(twin)
        while updated != twin {
            edges[updated].vertex = vertex
            updated = rotNext(updated)
        }
        let e1RotPrev = rotPrev(edge), e1RotNext = rotNext(edge)
        let e2RotPrev = rotPrev(twin), e2RotNext = rotNext(twin)
        edges[edges[e1RotNext].twin].next = e2RotPrev
        edges[e2RotPrev].prev = edges[e1RotNext].twin
        edges[e1RotPrev].prev = edges[e2RotNext].twin
        edges[edges[e2RotNext].twin].next = e1RotPrev
    }

    /// Removes the edges between vertices that are the same (128 ulps), drops the vertices left without edges,
    /// and closes the edge loops of the outer cells.
    fileprivate mutating func build() {
        var last = 0
        var it = 0
        while it < edges.count {
            defer { it += 2 }
            let v1 = edges[it].vertex, v2 = edges[edges[it].twin].vertex
            if v1 >= 0 && v2 >= 0 && ulpCompare(vertices[v1].x, vertices[v2].x, 128) == 0
                && ulpCompare(vertices[v1].y, vertices[v2].y, 128) == 0 {
                removeEdge(it)
                continue
            }
            if it != last {
                edges[last] = edges[it]
                edges[last + 1] = edges[it + 1]
                let e1 = last, e2 = last + 1
                edges[e1].twin = e2
                edges[e2].twin = e1
                if edges[e1].prev >= 0 {
                    edges[edges[e1].prev].next = e1
                    edges[edges[e2].next].prev = e2
                }
                if edges[e2].prev >= 0 {
                    edges[edges[e1].next].prev = e1
                    edges[edges[e2].prev].next = e2
                }
            }
            last += 2
        }
        edges.removeSubrange(last...)
        for e in edges.indices {
            cells[edges[e].cell].incidentEdge = e
            if edges[e].vertex >= 0 { vertices[edges[e].vertex].incidentEdge = e }
        }
        var lastVertex = 0
        for v in vertices.indices where vertices[v].incidentEdge >= 0 {
            if v != lastVertex {
                vertices[lastVertex] = vertices[v]
                let first = vertices[lastVertex].incidentEdge
                var e = first
                repeat {
                    edges[e].vertex = lastVertex
                    e = rotNext(e)
                } while e != first
            }
            lastVertex += 1
        }
        vertices.removeSubrange(lastVertex...)
        if vertices.isEmpty {
            guard !edges.isEmpty else { return }
            var k = 0
            var edge1 = k
            edges[edge1].next = edge1
            edges[edge1].prev = edge1
            k += 1
            edge1 = k
            k += 1
            while k < edges.count {
                let edge2 = k
                k += 1
                edges[edge1].next = edge2
                edges[edge1].prev = edge2
                edges[edge2].next = edge1
                edges[edge2].prev = edge1
                edge1 = k
                k += 1
            }
            edges[edge1].next = edge1
            edges[edge1].prev = edge1
        } else {
            for c in cells.indices where cells[c].incidentEdge >= 0 {
                let incident = cells[c].incidentEdge
                var left = incident
                while edges[left].prev >= 0 {
                    left = edges[left].prev
                    if left == incident { break }
                }
                if edges[left].prev >= 0 { continue }
                var right = incident
                while edges[right].next >= 0 { right = edges[right].next }
                edges[left].prev = right
                edges[right].next = left
            }
        }
    }
}

/// ulp_comparison<double>: -1 (a less), 0 (within maxUlps), 1 (a more).
private func ulpCompare(_ a: Double, _ b: Double, _ maxUlps: UInt64) -> Int {
    var la = a.bitPattern, lb = b.bitPattern
    if la < 0x8000_0000_0000_0000 { la = 0x8000_0000_0000_0000 &- la }
    if lb < 0x8000_0000_0000_0000 { lb = 0x8000_0000_0000_0000 &- lb }
    if la > lb { return la &- lb <= maxUlps ? 0 : -1 }
    return lb &- la <= maxUlps ? 0 : 1
}

private struct VoronoiSite {
    var x: Int32, y: Int32
    var sortedIndex = 0, initialIndex = 0
}

private struct VoronoiCircle {
    var x: Double = 0, y: Double = 0, lowerX: Double = 0
    var active = true
}

/// A beach line node: the breakpoint between two arcs.
private struct BeachNode {
    var left: VoronoiSite, right: VoronoiSite
    var edge: Int
    var circle = -1
}

private struct VoronoiBuilder {
    var sites: [VoronoiSite]
    var siteIndex = 0
    var nodes: [BeachNode] = []
    /// The beach line (std::map in the original): node indices in order, and each node's position in it.
    var line: [Int] = []
    var position: [Int] = []
    /// Circle events; the queue holds their indices (with their position, its ordering) as a libc++ binary heap.
    var circles: [VoronoiCircle] = []
    var queue: [Event] = []

    struct Event {
        var lowerX: Double, y: Double
        var circle: Int, node: Int
    }

    init(points: [(x: Int32, y: Int32)]) {
        sites = points.enumerated().map { VoronoiSite(x: $1.x, y: $1.y, initialIndex: $0) }
    }

    mutating func construct(_ output: inout VoronoiDiagram) {
        sites.libcxxSort { $0.x != $1.x ? $0.x < $1.x : $0.y < $1.y }
        var unique: [VoronoiSite] = []
        for s in sites where unique.last.map({ $0.x != s.x || $0.y != s.y }) ?? true { unique.append(s) }
        sites = unique
        for k in sites.indices { sites[k].sortedIndex = k }
        initBeachLine(&output)
        while !queue.isEmpty || siteIndex < sites.count {
            if queue.isEmpty {
                processSite(&output)
            } else if siteIndex == sites.count {
                processCircle(&output)
            } else if ulpCompare(Double(sites[siteIndex].x), queue[0].lowerX, 64) == -1 {
                processSite(&output)
            } else {
                processCircle(&output)
            }
            while !queue.isEmpty && !circles[queue[0].circle].active { _ = popEvent() }
        }
        output.build()
    }

    // MARK: Beach line

    private var head: Int { line.first ?? -1 }
    private var tail: Int { line.last ?? -1 }
    private func prev(_ n: Int) -> Int { position[n] > 0 ? line[position[n] - 1] : -1 }
    private func next(_ n: Int) -> Int { position[n] + 1 < line.count ? line[position[n] + 1] : -1 }

    /// Inserts `node` before the node `before` (at the end for -1), as the original's hinted std::map inserts do.
    private mutating func insert(_ node: BeachNode, before: Int) -> Int {
        let n = nodes.count
        nodes.append(node)
        position.append(0)
        let at = before >= 0 ? position[before] : line.count
        line.insert(n, at: at)
        for k in at..<line.count { position[line[k]] = k }
        return n
    }

    private mutating func erase(_ n: Int) {
        let at = position[n]
        line.remove(at: at)
        for k in at..<line.count { position[line[k]] = k }
    }

    /// std::map::lower_bound: the first node not before a new arc for `site`.
    private func lowerBound(_ site: VoronoiSite) -> Int {
        var lo = 0, hi = line.count
        while lo < hi {
            let mid = (lo + hi) / 2
            let n = nodes[line[mid]]
            if Self.nodeLess(n.left, n.right, site, site) { lo = mid + 1 } else { hi = mid }
        }
        return lo < line.count ? line[lo] : -1
    }

    // MARK: Events

    private mutating func initBeachLine(_ output: inout VoronoiDiagram) {
        if sites.isEmpty { return }
        if sites.count == 1 {
            output.cells.append(VoronoiDiagram.Cell(source: sites[0].initialIndex))
            siteIndex += 1
            return
        }
        var skip = 0
        while siteIndex < sites.count && sites[siteIndex].x == sites[0].x {
            siteIndex += 1
            skip += 1
        }
        if skip == 1 {
            _ = insertArc(sites[0], sites[0], sites[1], before: -1, &output)
            siteIndex += 1
        } else {
            for k in 0..<(siteIndex - 1) {
                let edge = output.insertEdge(sites[k], sites[k + 1]).0
                _ = insert(BeachNode(left: sites[k], right: sites[k + 1], edge: edge), before: -1)
            }
        }
    }

    private mutating func deactivateCircle(_ node: Int) {
        let c = nodes[node].circle
        if c >= 0 {
            circles[c].active = false
            nodes[node].circle = -1
        }
    }

    private mutating func processSite(_ output: inout VoronoiDiagram) {
        let site = sites[siteIndex]
        var right = lowerBound(site)
        if right < 0 {
            let left = tail
            let arc = nodes[left].right
            right = insertArc(arc, arc, site, before: right, &output)
            activateCircle(nodes[left].left, nodes[left].right, site, right)
        } else if right == head {
            let arc = nodes[right].left
            let left = insertArc(arc, arc, site, before: right, &output)
            activateCircle(site, nodes[right].left, nodes[right].right, right)
            right = left
        } else {
            let arc2 = nodes[right].left, site3 = nodes[right].right
            deactivateCircle(right)
            let left = prev(right)
            let arc1 = nodes[left].right, site1 = nodes[left].left
            let new = insertArc(arc1, arc2, site, before: right, &output)
            activateCircle(site1, arc1, site, new)
            activateCircle(site, arc2, site3, right)
        }
        siteIndex += 1
    }

    private mutating func processCircle(_ output: inout VoronoiDiagram) {
        let circle = queue[0].circle, node = queue[0].node
        var first = node
        var last = first
        let site3 = nodes[first].right
        let bisector2 = nodes[first].edge
        first = prev(first)
        let bisector1 = nodes[first].edge
        let site1 = nodes[first].left
        nodes[first].right = site3
        nodes[first].edge = output.insertEdge(site1, site3, circles[circle], bisector1, bisector2).0
        erase(last)
        last = first
        _ = popEvent()
        if first != head {
            deactivateCircle(first)
            first = prev(first)
            activateCircle(nodes[first].left, site1, site3, last)
        }
        last = next(last)
        if last >= 0 {
            deactivateCircle(last)
            activateCircle(site1, site3, nodes[last].right, last)
        }
    }

    private mutating func insertArc(_ arc1: VoronoiSite, _ arc2: VoronoiSite, _ site: VoronoiSite, before position: Int,
                                    _ output: inout VoronoiDiagram) -> Int {
        let (e1, e2) = output.insertEdge(arc2, site)
        let right = insert(BeachNode(left: site, right: arc2, edge: e2), before: position)
        return insert(BeachNode(left: arc1, right: site, edge: e1), before: right)
    }

    private mutating func activateCircle(_ s1: VoronoiSite, _ s2: VoronoiSite, _ s3: VoronoiSite, _ node: Int) {
        guard Self.orientation(s1, s2, s3) < 0 else { return }
        let c = Self.circle(s1, s2, s3)
        circles.append(c)
        queue.append(Event(lowerX: c.lowerX, y: c.y, circle: circles.count - 1, node: node))
        queue.libcxxPushHeap(by: Self.eventAfter)
        nodes[node].circle = circles.count - 1
    }

    private mutating func popEvent() -> Event {
        queue.libcxxPopHeap(by: Self.eventAfter)
    }

    /// The queue's ordering: the top is the first event (lowest x of the circle's rightmost point, then lowest y).
    private static func eventAfter(_ a: Event, _ b: Event) -> Bool {
        if b.lowerX != a.lowerX { return b.lowerX < a.lowerX }
        return b.y < a.y
    }

    // MARK: Predicates (voronoi_predicates for point sites)

    /// robust_cross_product: a1 * b2 - b1 * a2 from 64-bit magnitudes.
    private static func crossProduct(_ a1: Int64, _ b1: Int64, _ a2: Int64, _ b2: Int64) -> Double {
        let ua1 = a1.magnitude, ub1 = b1.magnitude, ua2 = a2.magnitude, ub2 = b2.magnitude
        let l = ua1 &* ub2, r = ub1 &* ua2
        if (a1 < 0) != (b2 < 0) {
            if (a2 < 0) != (b1 < 0) { return l > r ? -Double(l &- r) : Double(r &- l) }
            return -Double(l &+ r)
        }
        if (a2 < 0) != (b1 < 0) { return Double(l &+ r) }
        return l < r ? -Double(r &- l) : Double(l &- r)
    }

    /// orientation_test: -1 right turn, 0 collinear, 1 left turn.
    private static func orientation(_ p1: VoronoiSite, _ p2: VoronoiSite, _ p3: VoronoiSite) -> Int {
        let dx1 = Int64(p1.x) - Int64(p2.x), dx2 = Int64(p2.x) - Int64(p3.x)
        let dy1 = Int64(p1.y) - Int64(p2.y), dy2 = Int64(p2.y) - Int64(p3.y)
        let v = crossProduct(dx1, dy1, dx2, dy2)
        return v == 0 ? 0 : v < 0 ? -1 : 1
    }

    /// distance_predicate::pp: the new point's arc is closer to the left site's arc.
    private static func distanceLess(_ left: VoronoiSite, _ right: VoronoiSite, _ p: VoronoiSite) -> Bool {
        if left.x > right.x {
            if p.y <= left.y { return false }
        } else if left.x < right.x {
            if p.y >= right.y { return true }
        } else {
            return Int64(left.y) + Int64(right.y) < Int64(p.y) * 2
        }
        func distance(_ s: VoronoiSite) -> Double {
            let dx = Double(s.x) - Double(p.x), dy = Double(s.y) - Double(p.y)
            return (dx * dx + dy * dy) / (2.0 * dx)
        }
        return distance(left) < distance(right)
    }

    /// node_comparison_predicate for point sites.
    private static func nodeLess(_ l1: VoronoiSite, _ r1: VoronoiSite, _ l2: VoronoiSite, _ r2: VoronoiSite) -> Bool {
        let s1 = l1.sortedIndex > r1.sortedIndex ? l1 : r1
        let s2 = l2.sortedIndex > r2.sortedIndex ? l2 : r2
        if s1.x < s2.x { return distanceLess(l1, r1, s2) }
        if s1.x > s2.x { return !distanceLess(l2, r2, s1) }
        func comparisonY(_ l: VoronoiSite, _ r: VoronoiSite) -> (Int32, Int) {
            if l.sortedIndex == r.sortedIndex { return (l.y, 0) }
            if l.sortedIndex > r.sortedIndex { return (l.y, 1) }
            return (r.y, -1)
        }
        let y1 = comparisonY(l1, r1), y2 = comparisonY(l2, r2)
        if s1.sortedIndex == s2.sortedIndex { return y1 < y2 }
        if y1.0 != y2.0 { return y1.0 < y2.0 }
        return s1.sortedIndex < s2.sortedIndex ? y1.1 < 0 : y2.1 > 0
    }

    /// lazy_circle_formation_functor::ppp, falling back to mp_circle_formation_functor::ppp where the floating point
    /// result may be more than 64 ulps off.
    private static func circle(_ s1: VoronoiSite, _ s2: VoronoiSite, _ s3: VoronoiSite) -> VoronoiCircle {
        let x1 = Double(s1.x), y1 = Double(s1.y), x2 = Double(s2.x), y2 = Double(s2.y)
        let x3 = Double(s3.x), y3 = Double(s3.y)
        let difX1 = x1 - x2, difX2 = x2 - x3, difY1 = y1 - y2, difY2 = y2 - y3
        let orientation = crossProduct(Int64(s1.x) - Int64(s2.x), Int64(s2.x) - Int64(s3.x),
                                       Int64(s1.y) - Int64(s2.y), Int64(s2.y) - Int64(s3.y))
        let invOrientation = RobustFloat(0.5 / orientation, 2)
        let sumX1 = x1 + x2, sumX2 = x2 + x3, sumY1 = y1 + y2, sumY2 = y2 + y3
        let difX3 = x1 - x3, difY3 = y1 - y3
        var cx = RobustDifference(), cy = RobustDifference()
        cx += RobustFloat(difX1 * sumX1 * difY2, 2)
        cx += RobustFloat(difY1 * sumY1 * difY2, 2)
        cx -= RobustFloat(difX2 * sumX2 * difY1, 2)
        cx -= RobustFloat(difY2 * sumY2 * difY1, 2)
        cy += RobustFloat(difX2 * sumX2 * difX1, 2)
        cy += RobustFloat(difY2 * sumY2 * difX1, 2)
        cy -= RobustFloat(difX1 * sumX1 * difX2, 2)
        cy -= RobustFloat(difY1 * sumY1 * difX2, 2)
        var lowerX = cx
        lowerX -= RobustFloat(((difX1 * difX1 + difY1 * difY1) * (difX2 * difX2 + difY2 * difY2)
                               * (difX3 * difX3 + difY3 * difY3)).squareRoot(), 5)
        let dx = cx.difference, dy = cy.difference, dl = lowerX.difference
        var c = VoronoiCircle(x: dx.value * invOrientation.value, y: dy.value * invOrientation.value,
                              lowerX: dl.value * invOrientation.value)
        let recomputeX = dx.error > 64, recomputeY = dy.error > 64, recomputeLowerX = dl.error > 64
        if recomputeX || recomputeY || recomputeLowerX {
            exactCircle(s1, s2, s3, &c, recomputeX, recomputeY, recomputeLowerX)
        }
        return c
    }

    private static func exactCircle(_ s1: VoronoiSite, _ s2: VoronoiSite, _ s3: VoronoiSite, _ c: inout VoronoiCircle,
                                    _ recomputeX: Bool, _ recomputeY: Bool, _ recomputeLowerX: Bool) {
        let x1 = Int64(s1.x), y1 = Int64(s1.y), x2 = Int64(s2.x), y2 = Int64(s2.y), x3 = Int64(s3.x), y3 = Int64(s3.y)
        let difX = (ExtendedInt(x1 - x2), ExtendedInt(x2 - x3), ExtendedInt(x1 - x3))
        let difY = (ExtendedInt(y1 - y2), ExtendedInt(y2 - y3), ExtendedInt(y1 - y3))
        let sumX = (ExtendedInt(x1 + x2), ExtendedInt(x2 + x3))
        let sumY = (ExtendedInt(y1 + y2), ExtendedInt(y2 + y3))
        let invDenom = 0.5 / (difX.0 * difY.1 - difX.1 * difY.0).double
        let numer1 = difX.0 * sumX.0 + difY.0 * sumY.0
        let numer2 = difX.1 * sumX.1 + difY.1 * sumY.1
        if recomputeX || recomputeLowerX {
            let cx = numer1 * difY.1 - numer2 * difY.0
            c.x = cx.double * invDenom
            if recomputeLowerX {
                let sqrR = (difX.0 * difX.0 + difY.0 * difY.0) * (difX.1 * difX.1 + difY.1 * difY.1)
                    * (difX.2 * difX.2 + difY.2 * difY.2)
                let r = sqrR.double.squareRoot()
                if !(c.x < 0) {
                    c.lowerX = !(invDenom < 0) ? c.x + r * invDenom : c.x - r * invDenom
                } else {
                    let numer = cx * cx - sqrR
                    c.lowerX = numer.double * invDenom / (cx.double + r)
                }
            }
        }
        if recomputeY {
            let cy = numer2 * difX.0 - numer1 * difX.1
            c.y = cy.double * invDenom
        }
    }
}

/// robust_fpt<double>: a value with its relative error bound in ulps.
private struct RobustFloat {
    var value: Double, error: Double

    init(_ value: Double, _ error: Double = 0) {
        self.value = value
        self.error = error
    }

    static func += (a: inout RobustFloat, b: RobustFloat) {
        let v = a.value + b.value
        if (!(a.value < 0) && !(b.value < 0)) || (!(a.value > 0) && !(b.value > 0)) {
            a.error = (a.error < b.error ? b.error : a.error) + 1
        } else {
            var t = (a.value * a.error - b.value * b.error) / v
            if t < 0 { t = -t }
            a.error = t + 1
        }
        a.value = v
    }

    static func - (a: RobustFloat, b: RobustFloat) -> RobustFloat {
        let v = a.value - b.value
        if (!(a.value < 0) && !(b.value > 0)) || (!(a.value > 0) && !(b.value < 0)) {
            return RobustFloat(v, (a.error < b.error ? b.error : a.error) + 1)
        }
        var t = (a.value * a.error + b.value * b.error) / v
        if t < 0 { t = -t }
        return RobustFloat(v, t + 1)
    }
}

/// robust_dif<robust_fpt<double>>: a sum kept as its positive and negative parts.
private struct RobustDifference {
    var positive = RobustFloat(0), negative = RobustFloat(0)

    var difference: RobustFloat { positive - negative }

    static func += (a: inout RobustDifference, v: RobustFloat) {
        if !(v.value < 0) { a.positive += v } else { a.negative += RobustFloat(-v.value, v.error) }
    }

    static func -= (a: inout RobustDifference, v: RobustFloat) {
        if !(v.value < 0) { a.negative += v } else { a.positive += RobustFloat(-v.value, v.error) }
    }
}

/// extended_int<64>: sign and magnitude in 32-bit chunks, with boost's chunk arithmetic (its conversion to double
/// reads the top three chunks, so the chunk count matters, not just the value). The chunks are stored inline: the
/// circle formulas of 32-bit coordinates take at most 9 of boost's 64.
private struct ExtendedInt {
    static let maxChunks = 64
    var chunks = SIMD16<UInt32>()
    /// The number of chunks, negative for negative values.
    var count: Int

    init(_ v: Int64) {
        if v == 0 {
            count = 0
            return
        }
        let m = v.magnitude
        chunks[0] = UInt32(truncatingIfNeeded: m)
        chunks[1] = UInt32(truncatingIfNeeded: m >> 32)
        count = chunks[1] != 0 ? 2 : 1
        if v < 0 { count = -count }
    }

    private init() { count = 0 }

    var size: Int { abs(count) }

    /// extended_int::d.
    var double: Double {
        let sz = size
        var value = 0.0, exponent = 0
        if sz == 1 {
            value = Double(chunks[0])
        } else if sz == 2 {
            value = Double(chunks[1]) * 4_294_967_296.0 + Double(chunks[0])
        } else if sz >= 3 {
            for i in 1...3 {
                value *= 4_294_967_296.0
                value += Double(chunks[sz - i])
            }
            exponent = (sz - 3) << 5
        }
        if count < 0 { value = -value }
        return scalbn(value, exponent)
    }

    static func + (e1: ExtendedInt, e2: ExtendedInt) -> ExtendedInt {
        if e1.count == 0 { return e2 }
        if e2.count == 0 { return e1 }
        var r = ExtendedInt()
        if (e1.count > 0) != (e2.count > 0) {
            r.dif(e1.chunks, e1.size, e2.chunks, e2.size)
        } else {
            r.add(e1.chunks, e1.size, e2.chunks, e2.size)
        }
        if e1.count < 0 { r.count = -r.count }
        return r
    }

    static func - (e1: ExtendedInt, e2: ExtendedInt) -> ExtendedInt {
        if e1.count == 0 {
            var r = e2
            r.count = -r.count
            return r
        }
        if e2.count == 0 { return e1 }
        var r = ExtendedInt()
        if (e1.count > 0) != (e2.count > 0) {
            r.add(e1.chunks, e1.size, e2.chunks, e2.size)
        } else {
            r.dif(e1.chunks, e1.size, e2.chunks, e2.size)
        }
        if e1.count < 0 { r.count = -r.count }
        return r
    }

    static func * (e1: ExtendedInt, e2: ExtendedInt) -> ExtendedInt {
        if e1.count == 0 || e2.count == 0 { return ExtendedInt() }
        var r = ExtendedInt()
        r.mul(e1.chunks, e1.size, e2.chunks, e2.size)
        if (e1.count > 0) != (e2.count > 0) { r.count = -r.count }
        return r
    }

    private mutating func add(_ c1: SIMD16<UInt32>, _ sz1: Int, _ c2: SIMD16<UInt32>, _ sz2: Int) {
        if sz1 < sz2 {
            add(c2, sz2, c1, sz1)
            return
        }
        count = sz1
        var temp: UInt64 = 0
        for i in 0..<sz2 {
            temp += UInt64(c1[i]) + UInt64(c2[i])
            chunks[i] = UInt32(truncatingIfNeeded: temp)
            temp >>= 32
        }
        for i in sz2..<sz1 {
            temp += UInt64(c1[i])
            chunks[i] = UInt32(truncatingIfNeeded: temp)
            temp >>= 32
        }
        if temp != 0 && count != Self.maxChunks {
            chunks[count] = UInt32(truncatingIfNeeded: temp)
            count += 1
        }
    }

    private mutating func dif(_ c1: SIMD16<UInt32>, _ sz1In: Int, _ c2: SIMD16<UInt32>, _ sz2In: Int, _ rec: Bool = false) {
        var sz1 = sz1In, sz2 = sz2In
        if sz1 < sz2 {
            dif(c2, sz2, c1, sz1, true)
            count = -count
            return
        } else if sz1 == sz2 && !rec {
            repeat {
                sz1 -= 1
                if c1[sz1] < c2[sz1] {
                    sz1 += 1
                    dif(c2, sz1, c1, sz1, true)
                    count = -count
                    return
                } else if c1[sz1] > c2[sz1] {
                    sz1 += 1
                    break
                }
            } while sz1 != 0
            if sz1 == 0 {
                count = 0
                return
            }
            sz2 = sz1
        }
        count = sz1 - 1
        var flag = false
        for i in 0..<sz2 {
            chunks[i] = c1[i] &- c2[i] &- (flag ? 1 : 0)
            flag = c1[i] < c2[i] || (c1[i] == c2[i] && flag)
        }
        for i in sz2..<sz1 {
            chunks[i] = c1[i] &- (flag ? 1 : 0)
            flag = c1[i] == 0 && flag
        }
        if chunks[count] != 0 { count += 1 }
    }

    private mutating func mul(_ c1: SIMD16<UInt32>, _ sz1: Int, _ c2: SIMD16<UInt32>, _ sz2: Int) {
        var cur: UInt64 = 0
        count = min(Self.maxChunks, sz1 + sz2 - 1)
        for shift in 0..<count {
            var next: UInt64 = 0
            for first in 0...shift {
                if first >= sz1 { break }
                let second = shift - first
                if second >= sz2 { continue }
                let tmp = UInt64(c1[first]) * UInt64(c2[second])
                cur &+= UInt64(UInt32(truncatingIfNeeded: tmp))
                next &+= tmp >> 32
            }
            chunks[shift] = UInt32(truncatingIfNeeded: cur)
            cur = next &+ (cur >> 32)
        }
        if cur != 0 && count != Self.maxChunks {
            chunks[count] = UInt32(truncatingIfNeeded: cur)
            count += 1
        }
    }
}
